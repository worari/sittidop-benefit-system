export function normalizeSalaryLevel(value?: string): string {
  if (!value) return "น.3";
  const trimmed = value.trim();
  if (MILITARY_SALARY_TABLE[trimmed]) return trimmed;
  return "น.3";
}

export function formatSalaryStep(step: number): string {
  return Number.isInteger(step) ? step.toFixed(0) : step.toFixed(1);
}

export function getSalaryAmount(level: string, step: number): number {
  const normLevel = normalizeSalaryLevel(level);
  const table = MILITARY_SALARY_TABLE[normLevel];
  if (!table) return 35000;

  if (table[step] !== undefined) {
    return table[step];
  }

  // If exact step not in table, find closest or interpolate
  const steps = Object.keys(table).map(Number).sort((a, b) => a - b);
  if (steps.length === 0) return 35000;

  if (step <= steps[0]) return table[steps[0]];
  if (step >= steps[steps.length - 1]) return table[steps[steps.length - 1]];

  let lower = steps[0];
  let upper = steps[steps.length - 1];
  for (let i = 0; i < steps.length - 1; i++) {
    if (steps[i] <= step && steps[i + 1] >= step) {
      lower = steps[i];
      upper = steps[i + 1];
      break;
    }
  }

  if (lower === upper) return table[lower];
  const ratio = (step - lower) / (upper - lower);
  return Math.round(table[lower] + ratio * (table[upper] - table[lower]));
}

export function getCompensationAmount(level: string, compStep: number): number {
  if (compStep <= 0) return 0;
  const normLevel = normalizeSalaryLevel(level);
  const table = MILITARY_COMPENSATION_TABLE[normLevel];
  if (!table) return 0;

  if (table[compStep] !== undefined) {
    return table[compStep];
  }

  // Check closest
  const steps = Object.keys(table).map(Number).sort((a, b) => a - b);
  if (steps.length === 0) return 0;
  if (compStep <= steps[0]) return table[steps[0]];
  if (compStep >= steps[steps.length - 1]) return table[steps[steps.length - 1]];

  for (let i = 0; i < steps.length - 1; i++) {
    if (steps[i] <= compStep && steps[i + 1] >= compStep) {
      const lower = steps[i];
      const upper = steps[i + 1];
      const ratio = (compStep - lower) / (upper - lower);
      return Math.round(table[lower] + ratio * (table[upper] - table[lower]));
    }
  }

  return 0;
}

